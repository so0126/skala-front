// ============================================================
// 과제 12. Up-Down 숫자 맞추기 게임
//
// index.html의 "Up-Down 게임" 버튼을 누르면 startUpDown()이 실행됩니다.
//
// 참고: 교육자료에 맞춰 var를 사용했습니다.
//      요즘 실무에서는 값이 바뀌면 let, 안 바뀌면 const를 씁니다.
// ============================================================

// function: 여러 줄의 코드를 이름 하나로 묶어두는 상자입니다.
// 이렇게 묶어두면 파일을 읽는 순간이 아니라, 버튼을 누르는 순간에만 실행됩니다.
function startUpDown() {
  // 컴퓨터가 정한 비밀 숫자를 만듭니다. (과제 12 요구사항)
  // Math.random()  → 0 이상 1 미만의 무작위 소수 (예: 0.7213...)
  // * 50           → 0 이상 50 미만 (예: 36.06...)
  // Math.floor()   → 소수점을 버려 정수로 (예: 36) → 0 ~ 49
  // + 1            → 1 ~ 50
  var computerNum = Math.floor(Math.random() * 50) + 1;

  // 사용자가 몇 번 만에 맞췄는지 세는 변수입니다. 0부터 시작합니다.
  var count = 0;

  // while (true): 조건이 항상 참이라 그대로 두면 영원히 반복합니다.
  // 정답을 맞출 때까지 기회를 주기 위한 구조이고, 안에서 break로 빠져나옵니다. (과제 12 요구사항)
  while (true) {
    // prompt(): 입력창을 띄우고, 사용자가 적은 값을 돌려줍니다. (과제 12 요구사항)
    var input = prompt("1부터 50 사이의 숫자를 맞춰보세요!");

    // 사용자가 [취소]를 누르면 prompt는 null을 돌려줍니다.
    // 이 처리가 없으면 취소해도 게임이 안 끝나서 창이 계속 뜹니다.
    if (input === null) {
      alert("게임을 종료합니다. 정답은 " + computerNum + "이었습니다.");
      break; // break: 반복문을 즉시 빠져나옵니다.
    }

    // prompt는 사용자가 숫자를 적어도 항상 "글자"로 돌려줍니다.
    // 글자 "7"과 숫자 7은 다르기 때문에, Number()로 숫자로 바꿔야 크기 비교가 제대로 됩니다.
    var userNum = Number(input);

    // isNaN(): "숫자가 아니다(Not a Number)"인지 확인합니다.
    // 사용자가 "abc"나 빈칸을 넣었을 때 여기서 걸러집니다.
    if (isNaN(userNum) || userNum < 1 || userNum > 50) {
      alert("1부터 50 사이의 숫자만 입력할 수 있어요.");
      continue; // continue: 아래 코드를 건너뛰고 반복문 처음으로 돌아갑니다.
    }

    // 제대로 된 숫자를 넣었을 때만 횟수를 1 올립니다.
    // (잘못 입력한 것은 기회로 세지 않기 위해 continue 아래에 두었습니다.)
    count = count + 1;

    // 입력값이 정답보다 크면 숫자를 내려야 하므로 Down! (과제 12 요구사항)
    if (userNum > computerNum) {
      alert("Down!");

      // 입력값이 정답보다 작으면 숫자를 올려야 하므로 Up! (과제 12 요구사항)
    } else if (userNum < computerNum) {
      alert("Up!");

      // 위 두 경우가 아니면 = 정답입니다.
    } else {
      // + 기호로 글자와 변수를 이어 붙여 한 문장으로 만듭니다. (과제 12 요구사항)
      alert("축하합니다! " + count + "번 만에 맞추셨습니다.");
      break; // 정답을 맞췄으니 반복문을 끝냅니다.
    }
  }
}
