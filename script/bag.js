// ============================================================
// 과제 14. 내 가방 보기
//
// index.html의 "내 가방 보기" 버튼을 누르면 showMyBag()이 실행됩니다.
// 가방 속 물건을 JavaScript 객체로 만들고, 반복문으로 하나씩 꺼내 보여줍니다.
// ============================================================

// 객체(Object): 이름표(키)와 값을 짝지어 담는 상자입니다. 중괄호 { }로 만듭니다.
//   { name: "지갑", count: 1 }  →  name이라는 이름표에 "지갑", count라는 이름표에 1
//
// 배열(Array): 여러 개를 순서대로 담는 목록입니다. 대괄호 [ ]로 만듭니다.
//
// 아래 myBag은 "객체를 담은 배열"입니다. 물건 하나하나가 객체이고,
// 그 객체들이 배열 안에 순서대로 들어 있습니다. (과제 14 요구사항)
var myBag = [
  { name: "지갑", count: 1 },
  { name: "텀블러", count: 1 },
  { name: "리락쿠마 인형", count: 2 },
  { name: "카메라", count: 1 },
  { name: "립밤", count: 3 },
  { name: "다이어리", count: 1 }
];

// showMyBag: 가방 속 물건을 보여주는 함수입니다. (과제 14 요구사항)
function showMyBag() {
  // 보여줄 문장을 조금씩 이어 붙여 나갈 변수입니다. 제목부터 넣고 시작합니다.
  // \n: 줄바꿈 기호입니다. 두 번 쓰면 한 줄을 띄웁니다.
  var message = "내 가방 속 물건\n\n";

  // 물건이 몇 개인지 세는 변수입니다.
  var totalCount = 0;

  // for문으로 배열을 처음부터 끝까지 한 바퀴 돕니다. (과제 14 요구사항)
  // myBag.length는 배열에 든 물건 개수(6)입니다.
  for (var i = 0; i < myBag.length; i++) {
    // myBag[i]는 i번째 객체입니다. (i가 0이면 { name: "지갑", count: 1 })
    // 매번 myBag[i]라고 길게 쓰는 대신 item이라는 짧은 이름에 담아둡니다.
    var item = myBag[i];

    // 객체 안의 값을 꺼낼 때는 점(.)을 찍고 이름표를 적습니다.
    //   item.name  → "지갑"
    //   item.count → 1
    // i는 0부터 시작하므로, 사람이 읽는 번호로 만들려면 1을 더합니다.
    message = message + (i + 1) + ". " + item.name + " - " + item.count + "개\n";

    // 물건 수를 계속 더해 나갑니다.
    totalCount = totalCount + item.count;
  }

  // 반복문이 끝난 뒤 요약을 덧붙입니다.
  message = message + "\n총 " + myBag.length + "종류, " + totalCount + "개를 들고 다닙니다.";

  // 완성된 문장을 알림창으로 보여줍니다. (과제 14 요구사항)
  alert(message);
}
